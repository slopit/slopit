import type { BehavioralCaptureConfig } from "@slopit/behavioral";
import type { BehavioralData, CaptureFlag } from "@slopit/core";

/**
 * Configuration for slopit behavioral capture in jsPsych.
 */
export interface SlopitConfig extends BehavioralCaptureConfig {
  /**
   * Enable/disable slopit capture for this trial.
   * @default true
   */
  enabled?: boolean;

  /**
   * CSS selector for the input element to monitor.
   *
   * If not specified, the extension searches for textarea or text input elements.
   *
   * @default "textarea, input[type='text']"
   */
  targetSelector?: string;
}

/**
 * Data generated by slopit behavioral capture.
 */
export interface SlopitData {
  /**
   * Behavioral capture data including events and metrics.
   */
  behavioral: BehavioralData;

  /**
   * Flags generated during capture indicating potential AI-assisted responses.
   */
  flags: CaptureFlag[];
}
